"""Pure-Python logical menu model for a future Full HD BD-J Xlet.

No BDJO/JAR or playable menu is generated by this module. Indices are
zero-based logical selections to be resolved against authored MPLS/CLPI data.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

Screen = Literal['home', 'scenes', 'audio', 'subtitles', 'bonus']
Key = Literal['UP', 'DOWN', 'LEFT', 'RIGHT', 'ENTER', 'BACK', 'TOP_MENU']


@dataclass(frozen=True)
class MenuAction:
    kind: Literal['play', 'audio', 'subtitle', 'bonus']
    index: int


def _labels(items: tuple[str, ...], name: str) -> None:
    if len(items) > 999:
        raise ValueError(f'{name} count exceeds 999')
    for label in items:
        if not isinstance(label, str) or not (1 <= len(label.strip()) <= 80):
            raise ValueError(f'{name} labels must be 1..80 characters')
        if any(ord(ch) < 32 or ord(ch) == 127 for ch in label):
            raise ValueError(f'{name} contains a control character')


@dataclass(frozen=True)
class MenuSpec:
    chapters: tuple[str, ...]
    audio_tracks: tuple[str, ...] = ()
    subtitle_tracks: tuple[str, ...] = ()
    bonus_titles: tuple[str, ...] = ()
    profile: Literal['BD25', 'BD50'] = 'BD25'
    scenes_per_page: int = 6

    def __post_init__(self) -> None:
        if self.profile not in ('BD25', 'BD50'):
            raise ValueError('Only Full HD BD25/BD50 menu profiles are supported')
        if not isinstance(self.scenes_per_page, int) or isinstance(self.scenes_per_page, bool) or not 1 <= self.scenes_per_page <= 12:
            raise ValueError('scenes_per_page must be 1..12')
        if not self.chapters:
            raise ValueError('At least one chapter is required')
        for name in ('chapters', 'audio_tracks', 'subtitle_tracks', 'bonus_titles'):
            value = getattr(self, name)
            if not isinstance(value, tuple):
                raise ValueError(f'{name} must be a tuple')
            _labels(value, name)

    def manifest(self) -> dict:
        """Portable, deterministic logical manifest; not a BD-J/HDMV binary."""
        return {
            'schema_version': 1,
            'profile': self.profile,
            'chapters': [{'index': i, 'label': title} for i, title in enumerate(self.chapters)],
            'audio_tracks': [{'index': i, 'label': title} for i, title in enumerate(self.audio_tracks)],
            'subtitle_tracks': [{'index': i, 'label': title} for i, title in enumerate(self.subtitle_tracks)],
            'bonus_titles': [{'index': i, 'label': title} for i, title in enumerate(self.bonus_titles)],
            'scenes_per_page': self.scenes_per_page,
        }


class MenuController:
    """Deterministic model of remote control focus and actions.

    No command is sent to a player. A future BD-J adapter must map emitted
    logical track/chapter indices to actual authored playlist/stream IDs.
    """
    KEYS = frozenset(('UP', 'DOWN', 'LEFT', 'RIGHT', 'ENTER', 'BACK', 'TOP_MENU'))

    def __init__(self, spec: MenuSpec):
        self.spec = spec
        self.screen: Screen = 'home'
        self.page = 0
        self.focus = 0
        self.selected_audio = 0 if spec.audio_tracks else -1
        self.selected_subtitle = -1

    @property
    def home_entries(self) -> tuple[str, ...]:
        entries = ['play']
        if len(self.spec.chapters) > 1:
            entries.append('scenes')
        if self.spec.audio_tracks:
            entries.append('audio')
        if self.spec.subtitle_tracks:
            entries.append('subtitles')
        if self.spec.bonus_titles:
            entries.append('bonus')
        return tuple(entries)

    @property
    def pages(self) -> int:
        if self.screen != 'scenes':
            return 1
        return (len(self.spec.chapters) + self.spec.scenes_per_page - 1) // self.spec.scenes_per_page

    @property
    def entries(self) -> tuple[str, ...]:
        if self.screen == 'home':
            return self.home_entries
        if self.screen == 'scenes':
            start = self.page * self.spec.scenes_per_page
            return self.spec.chapters[start:start + self.spec.scenes_per_page]
        if self.screen == 'audio':
            return self.spec.audio_tracks
        if self.screen == 'subtitles':
            return ('Off',) + self.spec.subtitle_tracks
        return self.spec.bonus_titles

    def _home(self) -> None:
        self.screen = 'home'
        self.page = 0
        self.focus = 0

    def _open(self, name: str) -> None:
        self.screen = name  # type: ignore[assignment]
        self.page = 0
        self.focus = 0
        if name == 'audio' and self.selected_audio >= 0:
            self.focus = self.selected_audio
        elif name == 'subtitles':
            self.focus = self.selected_subtitle + 1

    def press(self, key: Key) -> MenuAction | None:
        if key not in self.KEYS:
            raise ValueError(f'Unsupported remote key: {key}')
        if key == 'TOP_MENU' or key == 'BACK':
            self._home()
            return None
        if key in ('UP', 'DOWN'):
            delta = -1 if key == 'UP' else 1
            self.focus = (self.focus + delta) % len(self.entries)
            return None
        if key in ('LEFT', 'RIGHT'):
            if self.screen == 'scenes':
                step = -1 if key == 'LEFT' else 1
                self.page = (self.page + step) % self.pages
                self.focus = 0
            return None
        if key != 'ENTER':
            return None
        if self.screen == 'home':
            selected = self.entries[self.focus]
            if selected == 'play':
                return MenuAction('play', 0)
            self._open(selected)
            return None
        if self.screen == 'scenes':
            chapter = self.page * self.spec.scenes_per_page + self.focus
            return MenuAction('play', chapter)
        if self.screen == 'audio':
            self.selected_audio = self.focus
            return MenuAction('audio', self.focus)
        if self.screen == 'subtitles':
            self.selected_subtitle = self.focus - 1
            return MenuAction('subtitle', self.selected_subtitle)
        return MenuAction('bonus', self.focus)

    def view(self) -> dict:
        return {
            'screen': self.screen,
            'page': self.page,
            'pages': self.pages,
            'focus': self.focus,
            'entries': list(self.entries),
            'selected_audio': self.selected_audio,
            'selected_subtitle': self.selected_subtitle,
        }
